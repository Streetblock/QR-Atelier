import { writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const PDF417Common = require('@zxing/library/cjs/core/pdf417/PDF417Common.js').default

const clusters = Array.from({ length: 3 }, () => new Array(929).fill(0))

for (let index = 0; index < PDF417Common.SYMBOL_TABLE.length; index += 1) {
  const mapped = PDF417Common.CODEWORD_TABLE[index] - 1
  const cluster = Math.floor(mapped / 929)
  const codeword = mapped % 929
  clusters[cluster][codeword] = PDF417Common.SYMBOL_TABLE[index]
}

if (clusters.some((cluster) => cluster.some((pattern) => pattern === 0))) {
  throw new Error('ZXing did not provide all 2,787 PDF417 codeword patterns.')
}

const lines = [
  '// Generated by scripts/generate-pdf417-patterns.mjs from the ISO/IEC 15438',
  '// symbol-character assignments exposed by ZXing (Apache-2.0).',
  '// Do not edit this table by hand.',
  '',
  'export const PDF417_CODEWORD_PATTERNS = Object.freeze([',
]

for (const cluster of clusters) {
  lines.push('  Object.freeze([')
  for (let index = 0; index < cluster.length; index += 16) {
    lines.push(`    ${cluster.slice(index, index + 16).join(', ')},`)
  }
  lines.push('  ]),')
}

lines.push('])', '')

const output = fileURLToPath(new URL('../libs/PDF417Patterns.js', import.meta.url))
await writeFile(output, lines.join('\n'))
