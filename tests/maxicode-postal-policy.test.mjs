import test from 'node:test';
import assert from 'node:assert/strict';
import { MaxiCodeCore } from '../libs/MaxiCodeCore.js';

const options = { mode: 2, postalCode: '12345', countryCode: '840', serviceClass: '001' };
const generate = overrides => new MaxiCodeCore('PAYLOAD', { ...options, ...overrides }).generate();

test('default US ZIP expansion is unchanged and literal policy preserves the prior native primary fields', () => {
  assert.deepEqual(generate(), generate({ mode2PostalCodePolicy: 'us-zip-plus4' }));
  assert.deepEqual(generate(), generate({ postalCode: '123450000', mode2PostalCodePolicy: 'literal' }));
  const literal = generate({ mode2PostalCodePolicy: 'literal' });
  // Captured independently from Toolkit 8d53996, not regenerated by this test.
  assert.deepEqual(Array.from(literal.codewords.slice(0, 10)), [18, 14, 48, 0, 0, 16, 1, 18, 7, 0]);
  assert.notDeepEqual(literal.codewords, generate().codewords);
  assert.notDeepEqual(literal.codewords, generate({ postalCode: '000012345' }).codewords);
});

test('postal policy changes no unrelated countries, lengths or modes and rejects unknown policies', () => {
  for (const overrides of [{ countryCode: '276' }, { postalCode: '1' }, { postalCode: '123456789' },
    { mode: 3, postalCode: 'ABC123' }, { mode: 4 }, { mode: 5 }]) {
    assert.deepEqual(generate(overrides), generate({ ...overrides, mode2PostalCodePolicy: 'literal' }));
  }
  for (const mode2PostalCodePolicy of ['guess', true, 42, {}, []]) {
    assert.throws(() => generate({ mode2PostalCodePolicy }), /postal-code policy/);
  }
});
